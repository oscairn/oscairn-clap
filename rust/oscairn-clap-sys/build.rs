//! Generates the raw bindings at build time with bindgen, from the repository's own
//! `include/oscairn-clap/*.h` against the vendored CLAP 1.2.10 headers (`rust/clap-headers`,
//! the same version Oscairn pins), and bakes the C layout facts (sizes, alignments, field
//! offsets) that `tests/layout.rs` asserts the Rust structs against.

use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let repo = manifest.join("../..");
    let oscairn_include = repo.join("include");
    let clap_include = manifest.join("../clap-headers");
    for dir in [&oscairn_include, &clap_include, &manifest.join("include"), &manifest.join("layout")] {
        println!("cargo:rerun-if-changed={}", dir.display());
    }
    println!("cargo:rerun-if-changed=build.rs");

    let bindings = bindgen::Builder::default()
        .header("include/oscairn_clap_bindgen.h")
        .clang_arg(format!("-I{}", oscairn_include.display()))
        .clang_arg(format!("-I{}", clap_include.display()))
        .constified_enum_module("oscairn_widget")
        .constified_enum_module("oscairn_role")
        .constified_enum_module("oscairn_field")
        .constified_enum_module("oscairn_chord_type")
        .derive_default(true)
        .layout_tests(false)
        .parse_callbacks(Box::new(bindgen::CargoCallbacks::new()))
        .generate()
        .expect("bindgen failed over the Oscairn CLAP headers");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    bindings
        .write_to_file(out.join("bindings.rs"))
        .expect("writing bindings.rs failed");

    generate_layout(&out, &oscairn_include, &clap_include);
}

// Compile and run `layout/layout_gen.c`; its stdout is the C side's truth.
fn generate_layout(out: &Path, oscairn_include: &Path, clap_include: &Path) {
    let status = cc::Build::new()
        .get_compiler()
        .to_command()
        .arg("-std=c11")
        .arg("-I")
        .arg(oscairn_include)
        .arg("-I")
        .arg(clap_include)
        .arg("layout/layout_gen.c")
        .arg("-o")
        .arg(out.join("layout_gen"))
        .status()
        .expect("compiling layout_gen.c failed (needs a C compiler)");
    assert!(status.success(), "compiling layout_gen.c failed");
    let output = std::process::Command::new(out.join("layout_gen"))
        .output()
        .expect("running layout_gen failed");
    assert!(output.status.success(), "running layout_gen failed");
    let report = String::from_utf8(output.stdout).expect("layout_gen printed non-UTF-8");

    let mut rust = String::from("// Generated by build.rs from layout_gen.c: C's own sizes and offsets.\n#[allow(clippy::all)]\npub fn assert_c_layout() {\n");
    for line in report.lines() {
        let mut it = line.split_whitespace();
        match it.next() {
            Some("S") => {
                let (name, size, align) = (it.next().unwrap(), it.next().unwrap(), it.next().unwrap());
                rust.push_str(&format!(
                    "    {{ let n = ::core::mem::size_of::<{name}>(); assert_eq!(n, {size}, \"{name} size\"); \
                     let a = ::core::mem::align_of::<{name}>(); assert_eq!(a, {align}, \"{name} align\"); }}\n"
                ));
            }
            Some("F") => {
                let (name, member, offset) = (it.next().unwrap(), it.next().unwrap(), it.next().unwrap());
                rust.push_str(&format!(
                    "    {{ let v = ::core::mem::MaybeUninit::<{name}>::zeroed(); let p = v.as_ptr(); \
                     assert_eq!(unsafe {{ ::core::ptr::addr_of!((*p).{member}) as usize - p as usize }}, \
                     {offset}, \"{name}.{member} offset\"); }}\n"
                ));
            }
            Some("C") => rust.push_str(&format!("    assert!({} == clap_sys::id::CLAP_INVALID_ID, \"CLAP_INVALID_ID\");\n", it.next().unwrap())),
            _ => panic!("unexpected layout_gen line: {line}"),
        }
    }
    rust.push_str("}\n");
    std::fs::write(out.join("c_layout.rs"), rust).expect("writing c_layout.rs failed");
}
